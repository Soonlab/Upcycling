def style_doc(path, line_numbers):
    doc = Document(path)
    for st in doc.styles:
        if st.type == 1 and st.font is not None:  # paragraph styles
            st.font.name = "Arial"
            rpr = st.element.get_or_add_rPr()
            fonts = rpr.find(qn("w:rFonts"))
            if fonts is None:
                fonts = OxmlElement("w:rFonts")
                rpr.append(fonts)
            for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
                fonts.set(qn(a), "Arial")
            for a in ("w:asciiTheme", "w:hAnsiTheme", "w:cstheme", "w:eastAsiaTheme"):
                if fonts.get(qn(a)) is not None:
                    del fonts.attrib[qn(a)]
    for name, size in (("Title", 16), ("Normal", 11), ("Body Text", 11), ("First Paragraph", 11), ("Compact", 8)):
        if name in [s.name for s in doc.styles]:
            doc.styles[name].font.size = Pt(size)
    for sec in doc.sections:
        sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
        sec.left_margin = sec.right_margin = Cm(2.0)
        sec.top_margin = sec.bottom_margin = Cm(2.0)
        sp = sec._sectPr
        if line_numbers and sp.find(qn("w:lnNumType")) is None:
            ln = OxmlElement("w:lnNumType")
            ln.set(qn("w:countBy"), "1")
            ln.set(qn("w:restart"), "continuous")
            ln.set(qn("w:distance"), "284")
            # lnNumType must precede pgNumType/cols/etc.; insert after pgMar when present
            pgmar = sp.find(qn("w:pgMar"))
            (pgmar.addnext(ln) if pgmar is not None else sp.append(ln))
        # centered page number in the footer
        p = sec.footer.paragraphs[0]
        if line_numbers and not p.runs:
            p.alignment = 1
            r = p.add_run()
            for tag, attr in (("w:fldChar", {"w:fldCharType": "begin"}), ("w:instrText", None),
                              ("w:fldChar", {"w:fldCharType": "end"})):
                el = OxmlElement(tag)
                if attr:
                    for k, v in attr.items():
                        el.set(qn(k), v)
                else:
                    el.set(qn("xml:space"), "preserve")
                    el.text = " PAGE "
                r._r.append(el)
    if line_numbers:  # new page before Tables, Figures and every figure image
        for para in doc.paragraphs:
            t = para.text.strip()
            if (para.style.name.startswith("Heading") and (t.startswith("Table 1 |") or t == "Figures")) \
                    or para._p.xpath(".//w:drawing"):
                if t != "" or para._p.xpath(".//w:drawing"):
                    para.paragraph_format.page_break_before = True
        # the first figure follows the 'Figures' heading directly
        heads = [q for q in doc.paragraphs if q.text.strip() == "Figures"]
        if heads:
            nxt = heads[0]._p.getnext()
            from docx.text.paragraph import Paragraph
            Paragraph(nxt, heads[0]._parent).paragraph_format.page_break_before = False
    doc.save(path)


