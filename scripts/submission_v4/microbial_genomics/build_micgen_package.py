def sub1(pattern, repl, text, flags=0):
    """re.sub that must match exactly once (guards against silent no-ops)."""
    new, n = re.subn(pattern, repl, text, count=1, flags=flags)
    assert n == 1, f"pattern not found: {pattern[:60]}"
    return new


def section(text, heading):
    """Return the body of '## heading' up to the next '## '."""
    m = re.search(rf"^## {re.escape(heading)}\n(.*?)(?=^## )", text, re.S | re.M)
    assert m, heading
    return m.group(1).strip()


